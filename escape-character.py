# Escape Characters
print("Hello, \"Alice\"!")  # Output: "Hello, \"Alice\"!"

print("Hello, 'Alice'!")  # Output: "Hello, 'Alice'!"   

print("Hello, \\Alice\\!")  # Output: "Hello, \Alice\!"

print("Hello, \nAlice!")  # Output: "Hello, Alice!"

print("Hello, \tAlice!")  # Output: "Hello, 	Alice!" 

print("Hello, \rAlice!")  # Output: "Hello, Alice!" 

print("Hello, \bAlice!")  # Output: "Hello, Alice!" 