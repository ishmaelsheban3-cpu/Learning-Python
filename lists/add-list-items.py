# Add List Items
my_list = ["apple", "banana", "cherry"]
my_list.append("date")
my_list.append("elderberry")
my_list.append("fig")   
print(my_list)  # Output: ['apple', 'banana', 'cherry', 'date', 'elderberry', 'fig']

# Explanation:
# In this code snippet, we define a list called 'my_list' that contains three string elements.
# We then add a new element "date" to the end of the list using the append() method.
# Finally, we print the updated list.   