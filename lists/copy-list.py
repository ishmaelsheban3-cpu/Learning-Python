# Copy a List
my_list = ["apple", "banana", "cherry"]
new_list = my_list.copy()
print(new_list)  # Output: ['apple', 'banana', 'cherry']

# Explanation:
# In this code snippet, we define a list called 'my_list' that contains three string elements.
# We then use the copy() method to create a new list called 'new_list' that contains the same elements as 'my_list'.
# Finally, we print the new list.