# Loop Through a List
my_list = ["apple", "banana", "cherry"]
for x in my_list:
    print(x)    

# Explanation:
# In this code snippet, we define a list called 'my_list' that contains three string elements.
# We then use a for loop to iterate through each element in the list and print it to the console. 
# The loop will print each fruit in the list one by one.  


# # Loop Through a List Using a While Loop
my_list = ["apple", "banana", "cherry"]
i = 0
while i < len(my_list):
    print(my_list[i])
    i += 1

    
