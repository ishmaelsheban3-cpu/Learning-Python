# Change List Items
my_list = ["apple", "banana", "cherry"]
my_list[1] = "blueberry"
my_list[0] = "avocado"
my_list[2] = "date"
print(my_list)  # Output: ['avocado', 'blueberry', 'date']  

# Explanation:
# In this code snippet, we define a list called 'my_list' that contains three string elements.
# We then change the value of the second element (at index 1) to "blueberry".
# Finally, we print the updated list.   