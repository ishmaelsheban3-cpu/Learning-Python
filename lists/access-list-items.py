# Access List Items
my_list = ["apple", "banana", "cherry"]
print(my_list[0])  # Output: apple
print(my_list[1])  # Output: banana
print(my_list[2])  # Output: cherry 

# Explanation:
# In this code snippet, we define a list called 'my_list' that contains three string
# elements: "apple", "banana", and "cherry". 
# We then access each element of the list using its index.   


# Another way to access list items is by using negative indexing, 
# which allows you to access elements from the end of the list. 
# For example:
print(my_list[-1])  # Output: cherry
print(my_list[-2])  # Output: banana
print(my_list[-3])  # Output: apple
