# Nested Dictionaries
my_dict = {
    "person1": {
        "name": "John",
        "age": 30,
        "city": "New York"
    },
    "person2": {
        "name": "Jane",
        "age": 25,
        "city": "Los Angeles"
    }
}

# Accessing nested values
print(my_dict["person1"]["name"])  # Output: John
print(my_dict["person2"]["age"])   # Output: 25 