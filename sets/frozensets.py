# Frozensets - A frozenset is an immutable version of a set. Once created, you cannot add or remove elements from a frozenset. Frozensets are hashable and can be used as keys in dictionaries or elements of other sets.   

frozen_set = frozenset([1, 2, 3, 4])
print(frozen_set)  # Output: frozenset({1, 2, 3, 4})    
