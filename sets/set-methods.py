# Set Methods
# sample set methods include add(), remove(), discard(), pop(), clear(), union(), intersection(), difference(), symmetric_difference(), issubset(), issuperset(), isdisjoint(), copy(), and frozenset(). These methods allow you to manipulate sets in various ways, such as adding or removing elements, performing set operations, and checking relationships between sets.       

# example of using set methods:
# Adding Elements to a Set
my_set = {1, 2, 3}
my_set.add(4)
print(my_set)  # Output: {1, 2, 3, 4}   