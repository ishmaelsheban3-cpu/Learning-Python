# Comparison Operators
x = 5
y = 10
print(x == y)  # Output: False
print(x != y)  # Output: True
print(x < y)   # Output: True
print(x > y)   # Output: False
print(x <= y)  # Output: True
print(x >= y)  # Output: False  

# another example:
a = 15
b = 20
print(a == b)  # Output: False
print(a != b)  # Output: True
print(a < b)   # Output: True
print(a > b)   # Output: False
print(a <= b)  # Output: True
print(a >= b)  # Output: False