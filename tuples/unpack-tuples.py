# Unpacking Tuple Elements
# example
sample_tuple = (1, 2, 3, 4, 5)

# Unpacking all elements
a, b, c, d, e = sample_tuple

print(a)  # Output: 1
print(b)  # Output: 2
print(c)  # Output: 3
print(d)  # Output: 4
print(e)  # Output: 5  


cars_model = ("Toyota", "Honda", "Ford")
brand1, brand2, brand3 = cars_model

print(brand1)  # Output: Toyota
print(brand2)  # Output: Honda
print(brand3)  # Output: Ford       