# Tuple Methods - count() and index()   
# example
sample_tuple = (1, 2, 3, 4, 5, 2, 3, 2) 

# Using count() method
count_of_2 = sample_tuple.count(2)
print(count_of_2)  # Output: 3

# Using index() method
index_of_3 = sample_tuple.index(3)
print(index_of_3)  # Output: 2

count_of_4 = sample_tuple.count(4)
print(count_of_4)  # Output: 1  