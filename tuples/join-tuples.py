# Joining Tuples
# example
tuple1 = (1, 2, 3)
tuple2 = (4, 5, 6)

# Joining tuples
joined_tuple = tuple1 + tuple2

print(joined_tuple)  # Output: (1, 2, 3, 4, 5, 6)       


# Another example
tuple3 = ("a", "b", "c")
tuple4 = ("d", "e", "f")

joined_tuple2 = tuple3 + tuple4

print(joined_tuple2)  # Output: (a, b, c, d, e, f)              