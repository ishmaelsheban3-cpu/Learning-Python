# Pass Statement
x = 10
y = 20

if x > y:
    pass
else:
    print("x is not greater than y")


# Explanation: 
# The pass statement is used as a placeholder in Python. 
# It does nothing and is often used in situations where a statement 
# is syntactically required but no action is needed. In this example, 
# if x is greater than y, the pass statement will be executed, 
# and nothing will happen. If x is not greater than y, 
# the else block will execute and print "x is not greater than y".